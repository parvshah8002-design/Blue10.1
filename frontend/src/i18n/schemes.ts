export const getMultilingualSchemeText = (
  schemeId: string,
  lang: Language,
  fallback: { name: string; simpleDescription: string; benefit: string; ministry: string }
): SchemeTextTranslation => {
  const trans = MULTILINGUAL_SCHEMES[schemeId]?.[lang];
  if (trans) return trans as SchemeTextTranslation;

  // Fallback to Hindi if not English and available, else original official text
  if (lang !== 'en' && MULTILINGUAL_SCHEMES[schemeId]?.['hi']) {
    return MULTILINGUAL_SCHEMES[schemeId]!['hi'] as SchemeTextTranslation;
  }
  return fallback;
};

export const getSchemeText = getMultilingualSchemeText;
